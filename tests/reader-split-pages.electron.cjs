const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { _electron, expect } = require('@playwright/test');
const { Resvg } = require('@resvg/resvg-js');
const { zip } = require('./helpers/documentFixtures.cjs');
const { pdf } = require('./android/filmstrip-fixtures.cjs');

test('packaged reader persists split halves and distinct bookmarks with unchanged folder/CBZ sources', { timeout:180000 }, async t => {
  const executable=path.resolve(process.env.OMICOMIC_PACKAGED_EXE||'release/local/2026-11-15-split-pages/win-unpacked/OmiComic.exe');
  await fs.mkdir(path.resolve('.cache/split-pages-20261115'),{recursive:true});
  const root=await fs.mkdtemp(path.resolve('.cache/split-pages-20261115/runtime-'));
  const book=path.join(root,'Split book');await fs.mkdir(book);
  const wide=new Resvg('<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="900"><path fill="#db5555" d="M0 0h600v900H0z"/><path fill="#347dc2" d="M600 0h600v900H600z"/></svg>').render().asPng();
  const portrait=new Resvg('<svg xmlns="http://www.w3.org/2000/svg" width="600" height="900"><path fill="#6a9c78" d="M0 0h600v900H0z"/></svg>').render().asPng();
  await fs.writeFile(path.join(book,'01.png'),wide);await fs.writeFile(path.join(book,'02.png'),portrait);await fs.writeFile(path.join(book,'03.png'),wide);
  const archive=path.join(root,'Split.cbz'),archiveBytes=zip([['01.png',wide],['02.png',portrait],['03.png',wide]]);await fs.writeFile(archive,archiveBytes);
  let app;
  t.after(async()=>{if(app)await app.close();assert.equal(path.dirname(root),path.resolve('.cache/split-pages-20261115'));await fs.rm(root,{recursive:true,force:true});});
  const env={...process.env,OMICOMIC_TEST_HEADLESS:'1',OMICOMIC_TEST_PROFILE:path.join(root,'profile')};delete env.ELECTRON_RUN_AS_NODE;delete env.VITE_DEV_SERVER_URL;
  const launch=async(file)=>{app=await _electron.launch({executablePath:executable,args:[file],env});const page=await app.firstWindow();await page.emulateMedia({reducedMotion:'reduce'});assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().some(w=>w.isVisible())),false);return page;};
  const input=page=>page.getByRole('textbox',{name:'跳转到页码'});
  const checks=[];
  for(const file of [path.join(book,'01.png'),archive]){
    let page=await launch(file);await expect(input(page)).toHaveValue('1');
    await page.getByRole('button',{name:'阅读设置',exact:true}).click();await page.getByRole('button',{name:'跨页拆分',exact:true}).click();await page.keyboard.press('Escape');
    await expect(input(page)).toHaveValue('1L');await page.getByRole('button',{name:'添加当前页书签',exact:true}).click();
    await page.getByRole('button',{name:'下一页',exact:true}).click();await expect(input(page)).toHaveValue('1R');await page.getByRole('button',{name:'添加当前页书签',exact:true}).click();
    const savedBookmarks=(await page.evaluate(()=>window.omicomic.getAppData())).data.bookmarks;
    const {sourcePath,resourceKey}=savedBookmarks[0];
    assert.ok(path.resolve(sourcePath).startsWith(root+path.sep));
    await expect.poll(async()=>{const data=(await page.evaluate(()=>window.omicomic.getAppData())).data;return data.readingProgress[resourceKey]?.readerViewState?.splitPageHalf;}).toBe('R');
    await app.close();app=null;page=await launch(file);await expect(input(page)).toHaveValue('1R');await expect(page.getByRole('button',{name:'取消当前页书签',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'上一页',exact:true}).click();await expect(input(page)).toHaveValue('1L');await expect(page.getByRole('button',{name:'取消当前页书签',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'尾页',exact:true}).click();await expect(input(page)).toHaveValue('3R');
    await page.getByRole('button',{name:'上一页',exact:true}).click();await expect(input(page)).toHaveValue('3L');
    await expect.poll(async()=>{const data=(await page.evaluate(()=>window.omicomic.getAppData())).data;const saved=data.readingProgress[resourceKey];return {index:saved?.currentPageIndex,half:saved?.readerViewState?.splitPageHalf,completed:saved?.completed};}).toEqual({index:2,half:'L',completed:false});
    await app.close();app=null;page=await launch(file===archive?archive:book);
    await expect(input(page)).toHaveValue('3L');
    const restored=(await page.evaluate(()=>window.omicomic.getAppData())).data;
    assert.equal(restored.readingProgress[resourceKey].completed,false);
    await page.getByRole('button',{name:'上一页',exact:true}).click();await expect(input(page)).toHaveValue('2');
    const data=(await page.evaluate(()=>window.omicomic.getAppData())).data;
    assert.equal(data.bookmarks.filter(b=>b.resourceKey===resourceKey).length,2);
    checks.push({source:file===archive?'CBZ':'folder',restore:'1R',distinctHalfBookmarks:2});
    await app.close();app=null;
  }
  assert.deepEqual(await fs.readFile(path.join(book,'01.png')),wide);assert.deepEqual(await fs.readFile(archive),archiveBytes);
  const document=path.join(root,'Spread.pdf'),pdfBytes=Buffer.from(pdf(3).toString().replaceAll('/MediaBox [0 0 400 600]','/MediaBox [0 0 800 600]'));
  await fs.writeFile(document,pdfBytes);
  let page=await launch(document);await expect(input(page)).toHaveValue('1');
  await page.getByRole('button',{name:'阅读设置',exact:true}).click();await page.getByRole('button',{name:'跨页拆分',exact:true}).click();await page.keyboard.press('Escape');
  await expect(input(page)).toHaveValue('1L');
  const canvas=page.locator('.reader-page-frame:not([aria-hidden="true"]) canvas.reader-pdf-canvas');await canvas.evaluate(el=>window.__splitCanvas=el);
  await page.getByRole('button',{name:'下一页',exact:true}).click();await expect(input(page)).toHaveValue('1R');
  assert.equal(await canvas.evaluate(el=>el===window.__splitCanvas),true);
  await page.getByRole('button',{name:'返回',exact:true}).click();await app.close();app=null;
  page=await launch(document);await expect(input(page)).toHaveValue('1R');
  assert.deepEqual(await fs.readFile(document),pdfBytes);checks.push({source:'PDF',restore:'1R',sharedCanvas:true});
  await app.close();app=null;
  await fs.writeFile('test-results/split-packaged.json',JSON.stringify({executable,hidden:true,checks,sourceBytesUnchanged:true},null,2));
});
