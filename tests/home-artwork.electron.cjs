const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { _electron, expect } = require('@playwright/test');

test('packaged home artwork imports local images, survives source moves and restarts, and restores the default', { timeout: 70000 }, async t => {
  const executable = path.resolve(process.env.OMICOMIC_PACKAGED_EXE || 'release/win-unpacked/OmiComic.exe');
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'omicomic-artwork-'));
  const profile = path.join(root, 'profile');
  await fs.mkdir(profile);
  const original = path.join(root, '自选插画.png'), moved = path.join(root, '原图已移动.png'), invalid = path.join(root, '损坏图片.png');
  await fs.copyFile('src/assets/home-scene.webp', path.join(root, '插画.webp'));
  const { Resvg } = require('@resvg/resvg-js');
  await fs.writeFile(original, new Resvg('<svg xmlns="http://www.w3.org/2000/svg" width="600" height="400"><rect width="600" height="400" fill="#91b5cf"/><circle cx="300" cy="200" r="140" fill="#e7bda0"/></svg>').render().asPng());
  await fs.writeFile(invalid, 'not an image');
  let electron;
  t.after(async () => {
    if (electron) await electron.close();
    assert.equal(path.dirname(root), path.resolve(os.tmpdir()));
    assert.ok(path.basename(root).startsWith('omicomic-artwork-'));
    await fs.rm(root, { recursive: true, force: true });
  });
  const env = { ...process.env, OMICOMIC_TEST_HEADLESS: '1', OMICOMIC_TEST_PROFILE: profile };
  delete env.ELECTRON_RUN_AS_NODE; delete env.VITE_DEV_SERVER_URL;
  const launch = async () => {
    electron = await _electron.launch({ executablePath: executable, args: [], env });
    const page = await electron.firstWindow();
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await expect(page.locator('.omi-home__art img')).toBeVisible(); return page;
  };
  let page = await launch();
  const version = await electron.evaluate(({ app }) => app.getVersion());
  assert.equal(version, require('../package.json').version);
  const defaultSource = await page.locator('.omi-home__art img').getAttribute('src');
  const select = async source => {
    await electron.evaluate(({ dialog }, source) => { dialog.showOpenDialog = async () => ({ canceled: source === null, filePaths: source ? [source] : [] }); }, source);
    return page.evaluate(() => window.omicomic.selectHomeArtwork());
  };
  assert.equal((await select(path.join(root, '插画.webp'))).ok, true, 'WebP is decoded by the shipped Electron runtime');
  const selected = await select(original);
  assert.equal(selected.ok, true, JSON.stringify(selected));
  assert.equal(selected.data.name, '自选插画.png');
  await assert.rejects(fs.access(path.join(profile, 'home-artwork.json')), 'selection alone does not commit');
  const committed = await page.evaluate(input => window.omicomic.saveHomeArtwork(input), { name:selected.data.name, sourceUrl:selected.data.url, crop:{x:.25,y:.25,width:.5,height:.5} });
  assert.equal(committed.ok, true, JSON.stringify(committed));
  const dimensions = await page.evaluate(async url => { const image = new Image(); image.src = url; await image.decode(); return [image.naturalWidth,image.naturalHeight]; }, committed.data.url);
  assert.deepEqual(dimensions,[300,200]);
  const saved = await fs.readFile(path.join(profile, 'home-artwork.json'), 'utf8');
  assert.equal((await page.evaluate(input => window.omicomic.saveHomeArtwork(input), {name:'bad',sourceUrl:selected.data.url,crop:{x:.9,y:0,width:.5,height:1}})).ok, false);
  assert.equal((await select(null)).data, null);
  assert.equal((await select(invalid)).ok, false);
  assert.equal(await fs.readFile(path.join(profile, 'home-artwork.json'), 'utf8'), saved, 'cancel and invalid input preserve the selected image');
  await fs.rename(original, moved);
  await electron.close(); electron = null;
  page = await launch();
  await expect(page.locator('.omi-home__art img')).toHaveAttribute('alt', '自选插画.png');
  await expect.poll(() => page.locator('.omi-home__art img').evaluate(img => img.complete && img.naturalWidth > 0)).toBe(true);
  assert.equal((await page.evaluate(() => window.omicomic.getHomeArtwork())).data.url, committed.data.url);
  assert.match(await page.locator('.omi-home__art img').evaluate(image=>getComputedStyle(image).maskImage),/linear-gradient/);
  await page.locator('.omi-home__library').click();
  await page.locator('.sidebar-settings-button').click(); await page.locator('#settings-category-appearance').click();
  const group = page.getByRole('region', { name: '主页看板娘', exact: true });
  await expect(group).toContainText('自选插画.png');
  await group.getByRole('button', {name:'调整裁剪',exact:true}).click();
  const cropDialog=page.getByRole('dialog',{name:'裁剪主页看板娘',exact:true});
  await expect(cropDialog.getByRole('spinbutton',{name:'裁剪宽度'})).toHaveValue('300');
  await cropDialog.getByRole('spinbutton',{name:'裁剪宽度'}).fill('240');
  await cropDialog.getByRole('button',{name:'取消',exact:true}).click();
  assert.equal(await fs.readFile(path.join(profile,'home-artwork.json'),'utf8'),saved);
  await group.getByRole('button', {name:'调整裁剪',exact:true}).click();
  await expect(cropDialog.getByRole('spinbutton',{name:'裁剪宽度'})).toHaveValue('300');
  await cropDialog.getByRole('button',{name:'原比例',exact:true}).click();
  await cropDialog.getByRole('button',{name:'保存图案',exact:true}).click();
  await expect(cropDialog).toHaveCount(0);
  assert.equal((await page.evaluate(() => window.omicomic.getHomeArtwork())).data.url,selected.data.url);
  await group.getByRole('button', { name: '恢复默认', exact: true }).click();
  await expect(group).toContainText('默认看板娘');
  await assert.rejects(fs.access(path.join(profile, 'home-artwork.json')));
  await fs.access(moved);
  await electron.close(); electron = null;
  page = await launch();
  await expect(page.locator('.omi-home__art img')).toHaveAttribute('src', defaultSource);
  await fs.mkdir('test-results', { recursive: true });
  await fs.writeFile('test-results/home-artwork-smoke.json', JSON.stringify({ executable, version, artworkPassed: true, sourceMovePassed: true, restartPassed: true, cancelAndInvalidPassed: true, cropDimensions:dimensions, recropFromSavedSourcePassed:true, resetPassed: true }, null, 2));
});
